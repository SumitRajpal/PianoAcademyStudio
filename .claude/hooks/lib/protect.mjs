/**
 * Files Claude may not edit, files that need the owner's OK, and shell commands that are blocked.
 * The same paths are also denied in .claude/settings.json, so a crashed hook leaves no gap.
 */

import { matches } from '../../../scripts/architecture/lib/glob.mjs';

const PROTECTED = [
  {
    globs: ['.env', '.env.*', '**/.env', '**/.env.*', '.envrc', '**/.envrc'],
    reason: 'Secret file (.env*). Claude never reads or edits these.',
  },
  {
    globs: [
      '**/*.keystore',
      '**/*.jks',
      '**/*.p12',
      '**/*.cer',
      '**/*.mobileprovision',
    ],
    reason:
      'Signing keys, certificates and provisioning profiles are off limits.',
  },
  {
    globs: ['ios/Pods/**'],
    reason:
      'ios/Pods is generated by CocoaPods. Change the Podfile instead and run `cd ios && pod install`.',
  },
  {
    globs: ['**/build/**', 'android/.gradle/**', '**/.cxx/**'],
    reason: 'Build output is generated. Change the source and rebuild.',
  },
  {
    globs: ['docs/architecture/graph.json'],
    reason:
      'graph.json is generated from the code. Run `npm run arch:build` instead of editing it.',
  },
  {
    globs: [
      'package-lock.json',
      'ios/Podfile.lock',
      'Gemfile.lock',
      'yarn.lock',
      'pnpm-lock.yaml',
    ],
    reason:
      'Lockfiles are written by the package manager. Use npm, pod or bundle commands instead of editing by hand.',
  },
];

const SETUP = ['.claude/**', 'scripts/architecture/config.mjs'];
const SETUP_EXCEPT = ['.claude/handoff/**', '.claude/state/**'];

export function protectedReason(rel) {
  return PROTECTED.find(p => matches(rel, p.globs))?.reason || null;
}

export function isSetupFile(rel) {
  return matches(rel, SETUP) && !matches(rel, SETUP_EXCEPT);
}

const SEP = '(?:^|[\\s;&|()])';
const BASH_RULES = [
  {
    re: new RegExp(
      `${SEP}git\\s+(?:-\\S+\\s+)*push\\b[^;&|\\n]*?(?:\\s--force(?:-with-lease)?\\b|\\s-f\\b|\\s-\\w*f\\w*\\b|\\s\\+\\S)`,
    ),
    reason: 'Force push is blocked. Push normally, or ask the owner to do it.',
  },
  {
    re: new RegExp(
      `${SEP}git\\s+(?:-\\S+\\s+)*branch\\b[^;&|\\n]*\\s(?:-d|-D|--delete)\\b`,
    ),
    reason: 'Deleting branches is blocked. Ask the owner to do it.',
  },
  {
    re: new RegExp(
      `${SEP}git\\s+(?:-\\S+\\s+)*push\\b[^;&|\\n]*(?:\\s--delete\\b|\\s-d\\b|\\s:\\S)`,
    ),
    reason: 'Deleting remote branches is blocked. Ask the owner to do it.',
  },
  {
    // Owner's rule: every build and run goes to the iPhone "Ramster", never a simulator.
    re: new RegExp(
      `${SEP}(?:xcrun\\s+simctl\\s+(?:boot|install|launch|io|openurl)\\b|open\\s+-a\\s+Simulator\\b|\\S*emulator\\s+-avd\\b)|-destination\\s+['"]?[^'"\\s]*[Ss]imulator|platform=iOS Simulator`,
    ),
    reason:
      'This project runs only on the iPhone 15 Plus "Ramster", never a simulator or emulator. Run `xcrun devicectl list devices` first; if Ramster is missing or unavailable, ask the owner to connect and unlock it. Device commands: .claude/rules/ios.md.',
  },
  {
    re: new RegExp(
      `${SEP}(?:npm\\s+run\\s+ios|(?:npx\\s+)?react-native\\s+run-ios)\\b(?![^;&|\\n]*--(?:device|udid)\\b)`,
    ),
    reason:
      '`run-ios` without --device starts a simulator, and this project runs only on the iPhone "Ramster". Use the device build in .claude/rules/ios.md (xcodebuild + devicectl), after checking `xcrun devicectl list devices`.',
  },
  {
    re: /(?:^|[\s'"=:/])\.env(?:rc|\.[\w.-]+)?(?=$|[\s'";|&)<>])/,
    reason:
      'This command touches a secret file (.env*). Claude never reads or edits these.',
  },
  {
    re: /\.(?:keystore|jks|p12|cer|mobileprovision)\b/,
    reason:
      'This command touches signing keys or certificates, which are off limits.',
  },
];

export function bashReason(command) {
  return BASH_RULES.find(r => r.re.test(command))?.reason || null;
}
